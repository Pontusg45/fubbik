#!/usr/bin/env bash
# Builds Apache AGE against the PostgreSQL the desktop app bundles, without
# installing into it, and prints a staging folder holding:
#   lib/age.dylib          -> bundle's lib/postgresql/
#   extension/age.control, extension/age--*.sql -> share/postgresql/extension/
#
# FUBBIK_POSTGRES_SRC  the Postgres tree (default: Postgres.app 18)
# FUBBIK_AGE_REF       the AGE git ref (default: the one docker/postgres uses)
# Cached in ~/Library/Caches/fubbik/age-<ref>; reruns reuse the build.
set -euo pipefail

pg_src="${FUBBIK_POSTGRES_SRC:-/Applications/Postgres.app/Contents/Versions/18}"
ref="${FUBBIK_AGE_REF:-PG18/v1.7.0-rc0}"
slug="${ref//\//-}"
cache="${HOME}/Library/Caches/fubbik/age-${slug}"
stage="${cache}/stage"
pg_config="${pg_src}/bin/pg_config"

[[ -x "$pg_config" ]] || { echo "build-age.sh: no pg_config at ${pg_config}" >&2; exit 1; }

if [[ -f "${stage}/lib/age.dylib" && -f "${stage}/extension/age.control" ]]; then
  echo "$stage"
  exit 0
fi

# AGE's grammar needs Bison 3; macOS's /usr/bin/bison is 2.3.
for candidate in /opt/homebrew/opt/bison/bin /usr/local/opt/bison/bin; do
  [[ -x "${candidate}/bison" ]] && export PATH="${candidate}:${PATH}"
done
bison_major="$(bison --version | head -1 | sed -E 's/.* ([0-9]+)\..*/\1/')"
if (( bison_major < 3 )); then
  echo "build-age.sh: AGE needs Bison 3 or newer (brew install bison)" >&2
  exit 1
fi

src="${cache}/src"
if [[ ! -d "${src}/.git" ]]; then
  mkdir -p "$cache"
  git clone --quiet --depth 1 --branch "$ref" https://github.com/apache/age.git "$src" >&2
fi

make -C "$src" PG_CONFIG="$pg_config" OPTFLAGS="" >&2
mkdir -p "${stage}/lib" "${stage}/extension"
built="$(find "$src" -maxdepth 1 \( -name 'age.dylib' -o -name 'age.so' \) | head -1)"
[[ -n "$built" ]] || { echo "build-age.sh: the build produced no age library" >&2; exit 1; }
cp "$built" "${stage}/lib/age.dylib"
cp "${src}/age.control" "${stage}/extension/"
# The install script for this version (generated by make as age--<v>.sql).
find "$src" -maxdepth 1 -name 'age--*.sql' -exec cp {} "${stage}/extension/" \;
echo "$stage"
